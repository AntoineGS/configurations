const assert = require("node:assert/strict")
const model = require("../plugins/menu/MenuModel.js")

assert.equal(model.launcherCardTop(1080, 399, 5, 28, 12), 40)
assert.equal(model.launcherCardTop(1080, 304, 5, 28, 12), 40)
assert.equal(model.launcherCardTop(720, 500, 5, 28, 12), 40)
assert.equal(model.launcherCardTop(720, 710, 5, 28, 12), 5)
assert.equal(model.launcherCardTop(0, 399, 5, 28, 12), 0)

assert.equal(model.launcherCardAvailableHeight(1080, 5, 28, 12), 1035)
assert.equal(model.launcherCardAvailableHeight(720, 5, 28, 12), 675)
assert.equal(model.launcherCardAvailableHeight(45, 5, 28, 12), 1)
assert.equal(model.launcherCardAvailableHeight(0, 5, 28, 12), 0)

assert.equal(model.rowsHaveIcons([]), false)
assert.equal(model.rowsHaveIcons([{ icon: "", appIcon: "" }]), false)
assert.equal(model.rowsHaveIcons([{ kind: "application", icon: "", appIcon: "" }]), true)
assert.equal(model.rowsHaveIcons([{ icon: "network", appIcon: "" }]), true)
assert.equal(model.rowsHaveIcons([{ icon: "", appIcon: "org.example.App" }]), true)

assert.equal(model.rowsHaveChevrons([]), false)
assert.equal(model.rowsHaveChevrons([{ kind: "action" }]), false)
assert.equal(model.rowsHaveChevrons([{ kind: "menu" }]), true)
assert.equal(model.rowsHaveChevrons([{ kind: "link" }]), true)

assert.equal(model.adaptiveMenuWidth(180, 40, 1000, 5), 220)
assert.equal(model.adaptiveMenuWidth(900, 40, 1000, 5), 750)
assert.equal(model.adaptiveMenuWidth(900, 40, 600, 80), 440)
assert.equal(model.adaptiveMenuWidth(0, 0, 1000, 5), 0)
assert.equal(model.adaptiveMenuWidth(-10, -20, 1000, 5), 0)
assert.equal(model.adaptiveMenuWidth(260, 40, 0, 5), 300)
assert.equal(model.adaptiveMenuWidth(Infinity, 40, 1000, 5), 40)
assert.equal(model.adaptiveMenuWidth(-Infinity, 40, 1000, 5), 40)
assert.equal(model.adaptiveMenuWidth(180, Infinity, 1000, 5), 180)
assert.equal(model.adaptiveMenuWidth(180, -Infinity, 1000, 5), 180)
assert.equal(model.adaptiveMenuWidth(180, 40, Infinity, 5), 220)
assert.equal(model.adaptiveMenuWidth(180, 40, -Infinity, 5), 220)
assert.equal(model.adaptiveMenuWidth(180, 40, 1000, Infinity), 220)
assert.equal(model.adaptiveMenuWidth(180, 40, 1000, -Infinity), 220)
assert.equal(model.adaptiveMenuWidth(NaN, 40, 1000, 5), 40)
assert.equal(model.adaptiveMenuWidth(180, NaN, 1000, 5), 180)
assert.equal(model.adaptiveMenuWidth(180, 40, NaN, 5), 220)
assert.equal(model.adaptiveMenuWidth(180, 40, 1000, NaN), 220)
