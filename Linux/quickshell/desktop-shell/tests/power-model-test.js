const assert = require("node:assert/strict")
const Model = require("../plugins/panels/power/Model.js")

assert.deepEqual(Model.profileNames(false), ["power-saver", "balanced"])
assert.deepEqual(Model.profileNames(true), ["power-saver", "balanced", "performance"])
assert.equal(Model.nativeBatteryPercent(true, 0.396), 40)
assert.equal(Model.nativeBatteryPercent(true, 1), 100)
assert.equal(Model.nativeBatteryPercent(false, 0.396), -1)
assert.equal(Model.nativeBatteryState(1), "charging")
assert.equal(Model.nativeBatteryState(4), "fully-charged")
assert.equal(Model.nativeBatteryState(5), "pending-charge")
assert.equal(Model.nativeProfileName(0), "power-saver")
assert.equal(Model.nativeProfileName(2), "performance")

assert.equal(Model.batteryPercentage("Battery 20%"), 20)
assert.equal(Model.isCharging("pending-charge"), true)
assert.equal(Model.isPluggedIn(false), true)
assert.equal(Model.isFullyCharged(100, "charging", false), true)
assert.equal(Model.batteryBarValue(50, "discharging", true), "50%")
assert.equal(Model.modeLabel("fully-charged"), "Fully charged")
